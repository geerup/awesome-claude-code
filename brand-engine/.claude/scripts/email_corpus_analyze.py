#!/usr/bin/env python3
"""email_corpus_analyze.py: catalog the MasterClass reference email corpus.

Scans the verbatim .eml reference corpus under references/masterclass-emails/ and writes an
INDEX.md next to it: a per-batch table (file, subject, signals) plus a summary tally. The analysis
is reproducible from the committed corpus, stdlib only, campaign-agnostic. It reads the corpus and
never modifies the .eml files. The corpus is external source material (see the folder README) and
is exempt from the house-style sweep; the subjects quoted in INDEX.md are verbatim.

Signals (heuristic, for triage, not a grade):
- multi: the email features two or more instructors (two or more "with <Name>" lines, or two or
  more digest section eyebrows like "Lessons For You" / "In This Issue").
- offer: the subject carries a promotion or urgency cue (percent, off, sale, ends, last chance).

Usage:
  python3 .claude/scripts/email_corpus_analyze.py            # write INDEX.md
  python3 .claude/scripts/email_corpus_analyze.py --print    # print the tally only, write nothing
"""

import email
import html
import os
import re
import sys
from email import policy
from email.header import decode_header, make_header
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1] / "references" / "masterclass-emails"
OFFER = re.compile(r"%|off|sale|save|ends|discount|deal|last chance|extended|final|today only|midnight", re.I)
WITH_LINE = re.compile(r"^\s*with [A-Z]")
SECTION = re.compile(r"(?im)^\s*(lessons for you|in this issue|just for you|new & noteworthy|member wins|instructor spotlight|coming soon)")


def html_to_text(h):
    h = re.sub(r"(?is)<(script|style|head).*?</\1>", " ", h)
    h = re.sub(r"(?is)<br\s*/?>", "\n", h)
    h = re.sub(r"(?is)</(p|div|tr|td|h1|h2|h3|li|table)>", "\n", h)
    h = re.sub(r"(?is)<[^>]+>", " ", h)
    h = html.unescape(h)
    h = re.sub(r"[ \t]+", " ", h)
    return re.sub(r"\n\s*\n\s*\n+", "\n\n", h).strip()


def subject_of(msg):
    raw = msg.get("Subject", "") or ""
    try:
        s = str(make_header(decode_header(raw)))
    except Exception:
        s = raw
    return re.sub(r"\s+", " ", s).strip()


def body_text(msg):
    bh = bt = None
    for part in msg.walk():
        ct = part.get_content_type()
        if ct == "text/html" and bh is None:
            try:
                bh = part.get_content()
            except Exception:
                bh = (part.get_payload(decode=True) or b"").decode("utf-8", "ignore")
        elif ct == "text/plain" and bt is None:
            try:
                bt = part.get_content()
            except Exception:
                bt = (part.get_payload(decode=True) or b"").decode("utf-8", "ignore")
    return html_to_text(bh) if bh else (bt or "")


def analyze_one(path):
    msg = email.message_from_bytes(path.read_bytes(), policy=policy.default)
    subj = subject_of(msg)
    text = body_text(msg)
    lines = text.split("\n")
    withs = sum(1 for ln in lines if WITH_LINE.match(ln))
    sections = len(SECTION.findall(text))
    multi = withs >= 2 or sections >= 2
    offer = bool(OFFER.search(subj))
    return {"subject": subj, "withs": withs, "multi": multi, "offer": offer}


def md_escape(s):
    return s.replace("|", "\\|").replace("\n", " ").strip()


def main():
    if not ROOT.is_dir():
        print("corpus not found at " + str(ROOT))
        return 2
    batches = sorted([d for d in ROOT.iterdir() if d.is_dir()])
    out = []
    out.append("# MasterClass reference corpus: index")
    out.append("")
    out.append("Generated by `scripts/email_corpus_analyze.py` from the verbatim `.eml` files in this")
    out.append("folder. Subjects are quoted verbatim from the source (external material, exempt from the")
    out.append("house-style sweep). The `multi` and `offer` columns are triage heuristics, defined in the")
    out.append("script, not a quality grade. Re-run the script to regenerate this file.")
    out.append("")
    tot_e = tot_m = tot_o = 0
    per_batch = []
    for bd in batches:
        files = sorted(bd.glob("*.eml"))
        if not files:
            continue
        rows = []
        bm = bo = 0
        for f in files:
            a = analyze_one(f)
            tags = []
            if a["multi"]:
                tags.append("multi")
            if a["offer"]:
                tags.append("offer")
            rows.append((f.name, a["subject"], a["withs"], " ".join(tags)))
            bm += 1 if a["multi"] else 0
            bo += 1 if a["offer"] else 0
        tot_e += len(files)
        tot_m += bm
        tot_o += bo
        per_batch.append((bd.name, len(files), bm, bo, rows))

    out.append("## Summary")
    out.append("")
    out.append("| Batch | Emails | Multi-instructor | Offer subject |")
    out.append("|---|---|---|---|")
    for name, n, m, o, _ in per_batch:
        out.append("| " + name + " | " + str(n) + " | " + str(m) + " | " + str(o) + " |")
    out.append("| TOTAL | " + str(tot_e) + " | " + str(tot_m) + " | " + str(tot_o) + " |")
    out.append("")
    for name, n, m, o, rows in per_batch:
        out.append("## " + name + " (" + str(n) + " emails, " + str(m) + " multi, " + str(o) + " offer)")
        out.append("")
        out.append("| File | Subject | with-lines | tags |")
        out.append("|---|---|---|---|")
        for fname, subj, withs, tags in rows:
            out.append("| " + md_escape(fname) + " | " + md_escape(subj) + " | " + str(withs) + " | " + tags + " |")
        out.append("")

    text = "\n".join(out) + "\n"
    print("corpus: " + str(tot_e) + " emails across " + str(len(per_batch)) + " batches; "
          + str(tot_m) + " multi-instructor, " + str(tot_o) + " offer-subject.")
    if "--print" in sys.argv:
        return 0
    (ROOT / "INDEX.md").write_text(text, encoding="utf-8")
    print("wrote " + str(ROOT / "INDEX.md"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
